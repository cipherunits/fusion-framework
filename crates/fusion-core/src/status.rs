pub fn is_informational(code: u16) -> bool {
    (100..200).contains(&code)
}

pub fn is_success(code: u16) -> bool {
    (200..300).contains(&code)
}

pub fn is_redirect(code: u16) -> bool {
    (300..400).contains(&code)
}

pub fn is_client_error(code: u16) -> bool {
    (400..500).contains(&code)
}

pub fn is_server_error(code: u16) -> bool {
    (500..600).contains(&code)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn success_alias_matches_ok() {
        assert_eq!(HTTP_SUCCESS, HTTP_200_OK);
        assert_eq!(HTTP_SUCCESS, 200);
    }

    #[test]
    fn classifiers() {
        assert!(is_success(HTTP_SUCCESS));
        assert!(is_client_error(HTTP_404_NOT_FOUND));
        assert!(is_server_error(HTTP_500_INTERNAL_SERVER_ERROR));
    }
}
